namespace App\Http\Controllers\Admin;

use App\Http\Controllers\Controller;
use App\Services\TotpService;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\Hash;

/**
 * The second factor of the admin account: a time based code (TOTP, RFC 6238) from an authenticator app, and ten recovery
 * codes. The secret is made when the page opens and only counts once a code from the app has been typed (enable).
 * To turn it off the password and a code (or a recovery code) are needed. A person who lost both is helped from the
 * server: php artisan admin:2fa-reset <username>.
 */
class SecurityController extends Controller
{
    public function index(Request $request)
    {
        $admin = Auth::guard('admin')->user();

        if ($admin->hasTwoFactorEnabled()) {
            return view(mailView('admin.security.index'), [
                'enabled'       => true,
                'recoveryCount' => count($admin->recoveryCodes()),
                'freshCodes'    => $request->session()->get('recovery_codes_fresh'),
            ]);
        }

        $totp = new TotpService();
        if ($admin->two_factor_secret === null) {
            $admin->forceFill(['two_factor_secret' => $totp->generateSecret()])->save();
        }

        return view(mailView('admin.security.index'), [
            'enabled' => false,
            'secret'  => $admin->two_factor_secret,
            'qrUri'   => $totp->getQrUri($admin->username, $admin->two_factor_secret),
        ]);
    }

    public function enable(Request $request)
    {
        $request->validate(['code' => ['required', 'string', 'digits:6']]);

        $admin = Auth::guard('admin')->user();
        if ($admin->hasTwoFactorEnabled() || $admin->two_factor_secret === null) {
            return redirect()->route('admin.security.index');
        }

        $totp = new TotpService();
        if (!$totp->verify($admin->two_factor_secret, $request->input('code'))) {
            return back()->withErrors(['code' => 'Invalid code. Check the time of your phone and try again.']);
        }

        $codes = $totp->generateRecoveryCodes();
        $admin->forceFill([
            'two_factor_recovery_codes' => json_encode($codes),
            'two_factor_enabled_at'     => now(),
        ])->save();

        return redirect()->route('admin.security.index')->with('recovery_codes_fresh', $codes);
    }

    public function disable(Request $request)
    {
        $request->validate([
            'password' => ['required', 'string'],
            'code'     => ['required', 'string', 'max:32'],
        ]);

        $admin = Auth::guard('admin')->user();
        if (!$admin->hasTwoFactorEnabled()) {
            return redirect()->route('admin.security.index');
        }

        if (!Hash::check($request->input('password'), $admin->password)) {
            return back()->withErrors(['password' => 'Wrong password.']);
        }

        $code  = trim((string) $request->input('code'));
        $valid = preg_match('/^\d{3}\s?\d{3}$/', $code)
            ? (new TotpService())->verify($admin->two_factor_secret, $code)
            : $admin->useRecoveryCode($code);
        if (!$valid) {
            return back()->withErrors(['code' => 'Invalid code.']);
        }

        $admin->clearTwoFactor();

        return redirect()->route('admin.security.index');
    }
}
